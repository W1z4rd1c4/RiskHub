#!/usr/bin/env node
/**
 * Generate the jsx-a11y deviation registry (ADR-013 · FR-P1-4) 1:1 from the
 * committed fingerprinted baseline.
 *
 * The deviation validator in `jsx-a11y-ratchet.mjs` (activated by the presence of
 * `scripts/a11y/jsx-a11y-deviations.json`) enforces an exact 1:1 mapping between
 * remaining baseline entries and deviation records, keyed by the same fingerprint
 * `rule|file|line|column`. This generator is the reproducible source of that file:
 * one record per baseline entry, each carrying an honest, rule-templated
 * `userImpact` + `reason`, an `owner`, a `tracking` label (the PM-owned epic), and
 * a `reviewBy` date.
 *
 * Every remaining baseline entry is PRE-EXISTING app-wide accessibility debt that
 * lives OUTSIDE the DORA changed-file audit scope (the changed files were fully
 * remediated in commit 5a). Re-run after any baseline `--write` so the registry
 * stays provably 1:1:
 *
 *   node scripts/a11y/generate-jsx-a11y-deviations.mjs
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { fingerprint, parseBaselineJson } from './jsx-a11y-ratchet.mjs';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const BASELINE_PATH = path.join(SCRIPT_DIR, 'jsx-a11y-baseline.json');
const DEVIATIONS_PATH = path.join(SCRIPT_DIR, 'jsx-a11y-deviations.json');

// Shared programme metadata. The tracking label is carried by a PM-owned epic.
const OWNER = 'frontend-platform';
const TRACKING = 'accessibility-baseline-debt';
const REVIEW_BY = '2027-01-12'; // ~2 quarters out from the 2026-07 audit.

const SHARED_RATIONALE =
  'pre-existing app-wide a11y debt outside the DORA changed-file audit scope; ' +
  'held by the fingerprinted jsx-a11y baseline and tracked for systematic remediation';

/** Honest, per-rule description of the user-facing accessibility impact. */
const USER_IMPACT_BY_RULE = {
  'jsx-a11y/label-has-for':
    'A form <label> does not both wrap and reference its control (the deprecated rule ' +
    'requires nesting + htmlFor). Where no other association exists, screen-reader users ' +
    'may not hear a reliable field name.',
  'jsx-a11y/control-has-associated-label':
    'An interactive control has no programmatic text label, so screen-reader users may ' +
    'encounter an unnamed control.',
  'jsx-a11y/click-events-have-key-events':
    'A click handler on a non-interactive element has no keyboard equivalent, so ' +
    'keyboard-only users cannot trigger the action.',
  'jsx-a11y/no-static-element-interactions':
    'A static element carries interaction handlers without an interactive role, so ' +
    'assistive technology does not expose it as actionable.',
  'jsx-a11y/label-has-associated-control':
    'A <label> has no associated form control, so its text is not exposed as a field ' +
    'name to assistive technology.',
  'jsx-a11y/no-autofocus':
    'autoFocus moves focus on mount, which can disorient screen-reader and keyboard ' +
    'users by skipping surrounding context.',
};

function userImpactFor(rule) {
  return USER_IMPACT_BY_RULE[rule] ?? 'Accessibility rule violation held by the baseline.';
}

async function main() {
  const raw = await fs.readFile(BASELINE_PATH, 'utf8');
  const entries = parseBaselineJson(raw);

  const deviations = entries
    .map((entry) => ({
      fingerprint: fingerprint(entry),
      rule: entry.rule,
      file: entry.file,
      userImpact: userImpactFor(entry.rule),
      reason: `Pre-existing ${entry.rule} — ${SHARED_RATIONALE}.`,
      owner: OWNER,
      tracking: TRACKING,
      reviewBy: REVIEW_BY,
    }))
    .sort((a, b) => (a.fingerprint < b.fingerprint ? -1 : a.fingerprint > b.fingerprint ? 1 : 0));

  const payload = {
    _comment:
      'ADR-013 FR-P1-4 jsx-a11y deviation registry. One record per remaining baseline ' +
      'entry, keyed 1:1 by fingerprint (rule|file|line|column). Generated by ' +
      'scripts/a11y/generate-jsx-a11y-deviations.mjs from jsx-a11y-baseline.json — do not ' +
      'hand-edit; re-run after any baseline --write.',
    generatedAt: new Date().toISOString(),
    count: deviations.length,
    deviations,
  };

  await fs.writeFile(DEVIATIONS_PATH, `${JSON.stringify(payload, null, 2)}\n`, 'utf8');
  console.log(`jsx-a11y deviations written: ${deviations.length} records -> ${path.basename(DEVIATIONS_PATH)}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
